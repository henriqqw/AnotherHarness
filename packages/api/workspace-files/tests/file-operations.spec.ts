/** Spec workspace/0001 AC-6, AC-11: create, rename, and delete from the Files tree. */
import { mkdir, readFile, readdir, symlink, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { failureOf, openWorkspace, signal, type Harness } from './harness.ts'

let h: Harness
afterEach(async () => { await h.dispose() })

describe('workspaceFiles.create', () => {
  it('creates a file with content and an empty directory, and wakes the change feed for files', async () => {
    h = await openWorkspace('wf-ops-')
    const files = h.endpoint()
    const observed = vi.fn()
    h.ctx.on('fs/observed', observed)
    const created = await files.create(h.scope, 'notes.md', 'file', '# hi\n', signal())
    expect(await readFile(join(h.workspace, 'notes.md'), 'utf8')).toBe('# hi\n')
    expect(created).toMatchObject({ absolutePath: join(h.workspace, 'notes.md'), bytes: 5 })
    expect(observed).toHaveBeenCalledWith(expect.anything(), { kind: 'present', version: created.version }, undefined)
    await files.create(h.scope, 'empty.txt', 'file', undefined, signal())
    expect(await readFile(join(h.workspace, 'empty.txt'), 'utf8')).toBe('')
    await files.create(h.scope, 'src', 'directory', 'ignored', signal())
    expect(await readdir(join(h.workspace, 'src'))).toEqual([])
    await files.create(h.scope, 'deep/er/file.ts', 'file', 'x', signal())
    await files.create(h.scope, 'a/b/c', 'directory', undefined, signal())
    expect(await readFile(join(h.workspace, 'deep', 'er', 'file.ts'), 'utf8')).toBe('x')
    expect(await readdir(join(h.workspace, 'a', 'b', 'c'))).toEqual([])
  })

  it('AC-6: refuses taken paths, missing parents, outside paths, and oversized or binary content', async () => {
    h = await openWorkspace('wf-ops-')
    await writeFile(join(h.workspace, 'taken.txt'), 'x')
    const files = h.endpoint({ maxEditableBytes: 4 })
    expect(await failureOf(files.create(h.scope, 'taken.txt', 'file', '', signal())))
      .toEqual({ code: 'workspace-file/exists', details: { path: 'taken.txt' } })
    expect((await failureOf(files.create(h.scope, 'taken.txt/child', 'directory', undefined, signal()))).code).toBe('workspace-file/not-found')
    expect((await failureOf(files.create(h.scope, join(h.outside, 'x.txt'), 'file', '', signal()))).code)
      .toBe('workspace-file/outside-workspace')
    expect((await failureOf(files.create(h.scope, 'big.txt', 'file', 'too long', signal()))).code).toBe('workspace-file/too-large')
    expect((await failureOf(files.create(h.scope, 'nul.txt', 'file', 'a\u0000', signal()))).code).toBe('workspace-file/not-text')
    expect((await failureOf(files.create(h.scope, '', 'file', '', signal()))).code).toBe('gateway/bad-request')
  })
})

describe('workspaceFiles.rename', () => {
  it('moves files and directories and reports the new location', async () => {
    h = await openWorkspace('wf-ops-')
    await writeFile(join(h.workspace, 'a.txt'), 'A')
    await mkdir(join(h.workspace, 'dir'))
    await writeFile(join(h.workspace, 'dir', 'inner.txt'), 'I')
    const files = h.endpoint()
    const observed = vi.fn()
    h.ctx.on('fs/observed', observed)
    const moved = await files.rename(h.scope, 'a.txt', 'b.txt', signal())
    expect(await readFile(join(h.workspace, 'b.txt'), 'utf8')).toBe('A')
    expect(moved.absolutePath).toBe(join(h.workspace, 'b.txt'))
    expect(observed).toHaveBeenCalledWith(expect.anything(), { kind: 'absent' }, undefined)
    expect(observed).toHaveBeenCalledWith(expect.anything(), { kind: 'present', version: moved.version }, undefined)
    observed.mockClear()
    await files.rename(h.scope, 'dir', 'folder', signal())
    expect(await readFile(join(h.workspace, 'folder', 'inner.txt'), 'utf8')).toBe('I')
    expect(observed).toHaveBeenCalledTimes(1)
  })

  it('AC-6: refuses taken targets, links, the root, outside targets, and an empty target', async () => {
    h = await openWorkspace('wf-ops-')
    await writeFile(join(h.workspace, 'a.txt'), 'A')
    await writeFile(join(h.workspace, 'b.txt'), 'B')
    await symlink(join(h.workspace, 'a.txt'), join(h.workspace, 'link.txt'))
    const files = h.endpoint()
    expect(await failureOf(files.rename(h.scope, 'a.txt', 'b.txt', signal())))
      .toEqual({ code: 'workspace-file/exists', details: { path: 'b.txt' } })
    expect((await failureOf(files.rename(h.scope, 'link.txt', 'c.txt', signal()))).code).toBe('workspace-file/not-regular-file')
    expect((await failureOf(files.rename(h.scope, '.', 'moved', signal()))).code).toBe('gateway/bad-request')
    expect((await failureOf(files.rename(h.scope, 'a.txt', join(h.outside, 'a.txt'), signal()))).code).toBe('workspace-file/outside-workspace')
    expect((await failureOf(files.rename(h.scope, 'a.txt', '', signal()))).code).toBe('gateway/bad-request')
    expect((await failureOf(files.rename(h.scope, 'missing.txt', 'x.txt', signal()))).code).toBe('workspace-file/not-found')
    expect(await readFile(join(h.workspace, 'a.txt'), 'utf8')).toBe('A')
  })
})

describe('workspaceFiles.deleteEntry', () => {
  it('deletes files, empty directories, and non-empty directories only with recursive', async () => {
    h = await openWorkspace('wf-ops-')
    await writeFile(join(h.workspace, 'a.txt'), 'A')
    await mkdir(join(h.workspace, 'empty'))
    await mkdir(join(h.workspace, 'full'))
    await writeFile(join(h.workspace, 'full', 'x.txt'), 'X')
    const files = h.endpoint()
    expect(await files.deleteEntry(h.scope, 'a.txt', false, signal())).toEqual({ removed: true })
    await files.deleteEntry(h.scope, 'empty', false, signal())
    expect(await failureOf(files.deleteEntry(h.scope, 'full', false, signal())))
      .toEqual({ code: 'workspace-file/not-empty', details: { path: 'full' } })
    await files.deleteEntry(h.scope, 'full', true, signal())
    expect(await readdir(h.workspace)).toEqual([])
  })

  it('AC-6: refuses links, the root, and missing entries', async () => {
    h = await openWorkspace('wf-ops-')
    await writeFile(join(h.workspace, 'real.txt'), 'R')
    await symlink(join(h.workspace, 'real.txt'), join(h.workspace, 'link.txt'))
    const files = h.endpoint()
    expect((await failureOf(files.deleteEntry(h.scope, 'link.txt', false, signal()))).code).toBe('workspace-file/not-regular-file')
    expect((await failureOf(files.deleteEntry(h.scope, '.', true, signal()))).code).toBe('gateway/bad-request')
    expect((await failureOf(files.deleteEntry(h.scope, 'missing', false, signal()))).code).toBe('workspace-file/not-found')
    expect(await readFile(join(h.workspace, 'real.txt'), 'utf8')).toBe('R')
  })

  it('maps sandbox refusals, races, and other failures', async () => {
    h = await openWorkspace('wf-ops-')
    await writeFile(join(h.workspace, 'a.txt'), 'A')
    const files = h.endpoint()
    const remove = vi.spyOn(h.ctx.fs, 'remove')
    const fail = (code: string) => Object.assign(new Error(code), { code })
    remove.mockRejectedValueOnce(fail('FS_SANDBOX_DENIED'))
    expect((await failureOf(files.deleteEntry(h.scope, 'a.txt', false, signal()))).code).toBe('workspace-file/write-denied')
    remove.mockRejectedValueOnce(fail('FS_NOT_FOUND'))
    expect((await failureOf(files.deleteEntry(h.scope, 'a.txt', false, signal()))).code).toBe('workspace-file/not-found')
    remove.mockRejectedValueOnce(new Error('disk gone'))
    await expect(files.deleteEntry(h.scope, 'a.txt', false, signal())).rejects.toThrow('disk gone')
    const rename = vi.spyOn(h.ctx.fs, 'rename').mockRejectedValueOnce(fail('FS_EXISTS'))
    expect((await failureOf(files.rename(h.scope, 'a.txt', 'b.txt', signal()))).code).toBe('workspace-file/exists')
    rename.mockRestore()
    vi.spyOn(h.ctx.fs, 'writeText').mockRejectedValueOnce(fail('FS_NOT_OBSERVED'))
    expect((await failureOf(files.create(h.scope, 'race.txt', 'file', '', signal()))).code).toBe('workspace-file/exists')
    vi.spyOn(h.ctx.fs, 'stat').mockResolvedValueOnce(undefined)
    expect((await failureOf(files.create(h.scope, 'gone', 'directory', undefined, signal()))).code).toBe('workspace-file/not-found')
  })
})
